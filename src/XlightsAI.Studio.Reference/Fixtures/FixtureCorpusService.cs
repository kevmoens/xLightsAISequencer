using System.Security.Cryptography;

namespace XlightsAI.Studio.Reference.Fixtures;

/// <summary>One fixture whose on-disk file hash no longer matches what the manifest recorded, or is missing.</summary>
public sealed record FixtureHashMismatch(string FixtureId, string RelativePath, string RecordedSha256, string? ActualSha256);

/// <summary>
/// Outcome of auditing the fixture corpus: the parsed manifest (if any), validation errors, and any
/// drift between recorded and actual on-disk hashes.
/// </summary>
public sealed record FixtureCorpusAuditReport(
    FixtureCorpusManifest? Manifest,
    FixtureCorpusValidationResult Validation,
    IReadOnlyList<FixtureHashMismatch> HashMismatches)
{
    public bool IsAccepted => Validation.IsValid && HashMismatches.Count == 0;

    /// <summary>Human-readable summary: the "public output" a Settings/Diagnostics screen can display verbatim.</summary>
    public string ToDisplayText()
    {
        if (!Validation.IsValid || Manifest is null)
        {
            return "Fixture corpus manifest is INVALID:" + Environment.NewLine
                + string.Join(Environment.NewLine, Validation.Errors.Select(e => $"  - {e}"));
        }

        var byKind = Manifest.Fixtures
            .GroupBy(f => f.Kind)
            .Select(g => $"{g.Key}: {g.Count()}");

        var mismatchText = HashMismatches.Count == 0
            ? "none"
            : string.Join(", ", HashMismatches.Select(m => $"{m.FixtureId} (recorded {m.RecordedSha256}, actual {m.ActualSha256 ?? "MISSING"})"));

        return $"""
            Fixture corpus: {Manifest.Fixtures.Count} fixtures, generated by {Manifest.GeneratedByTool} {Manifest.GeneratedWithToolVersion}
              Generated:  {Manifest.GeneratedUtc:u}
              By kind:    {string.Join(", ", byKind)}
              Hash drift: {mismatchText}
            """;
    }
}

/// <summary>
/// Application-layer orchestration for Step 003: reads the fixture corpus manifest, validates it
/// against this Studio's contract rules, and — when <paramref name="fixturesRootDir"/> is supplied —
/// re-hashes every referenced file on disk to detect drift from what was recorded. This is the
/// mechanism that proves "repeatable invocation": the committed files must still hash to exactly
/// what the manifest recorded. Owns no UI and never writes to the fixture files it inspects.
/// </summary>
public sealed class FixtureCorpusService(IFixtureCorpusManifestReader reader)
{
    public async Task<FixtureCorpusAuditReport> AuditAsync(string manifestPath, string? fixturesRootDir, CancellationToken ct)
    {
        FixtureCorpusManifest manifest;
        try
        {
            manifest = await reader.ReadAsync(manifestPath, ct).ConfigureAwait(false);
        }
        catch (Exception ex) when (ex is FileNotFoundException or FixtureCorpusManifestFormatException)
        {
            return new FixtureCorpusAuditReport(
                Manifest: null,
                Validation: FixtureCorpusValidationResult.Failure([ex.Message]),
                HashMismatches: []);
        }

        var validation = FixtureCorpusValidator.Validate(manifest);

        var mismatches = fixturesRootDir is null
            ? []
            : await ComputeHashMismatchesAsync(manifest, fixturesRootDir, ct).ConfigureAwait(false);

        return new FixtureCorpusAuditReport(manifest, validation, mismatches);
    }

    private static async Task<IReadOnlyList<FixtureHashMismatch>> ComputeHashMismatchesAsync(
        FixtureCorpusManifest manifest, string fixturesRootDir, CancellationToken ct)
    {
        var mismatches = new List<FixtureHashMismatch>();

        foreach (var fixture in manifest.Fixtures)
        {
            if (string.IsNullOrWhiteSpace(fixture.RelativePath))
            {
                continue;
            }

            var fullPath = Path.Combine(fixturesRootDir, fixture.RelativePath);
            if (!File.Exists(fullPath))
            {
                mismatches.Add(new FixtureHashMismatch(fixture.Id, fixture.RelativePath, fixture.Sha256, ActualSha256: null));
                continue;
            }

            await using var stream = File.OpenRead(fullPath);
            var actualHash = Convert.ToHexString(await SHA256.HashDataAsync(stream, ct).ConfigureAwait(false));
            if (!string.Equals(actualHash, fixture.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                mismatches.Add(new FixtureHashMismatch(fixture.Id, fixture.RelativePath, fixture.Sha256, actualHash));
            }
        }

        return mismatches;
    }
}
