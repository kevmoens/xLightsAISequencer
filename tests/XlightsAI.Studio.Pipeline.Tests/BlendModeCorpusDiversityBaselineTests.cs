namespace XlightsAI.Studio.Pipeline.Tests;

/// <summary>
/// Build-plan Phase 30 step 30.1's own acceptance-definition requirement: "N set from mined corpus data
/// in step 30.1; record the chosen value and its source in evidence." This scans the same real,
/// author-created corpus 30.0 used (<c>C:\xLights\*.xsq</c>, 35 real multi-year family show files) --
/// directly via <see cref="EffectAlignmentParser"/> (structural XML parsing only, no audio analysis
/// needed, since a raw <c>T_CHOICE_LayerMethod</c> settings-string reading requires no beat grid) -- and
/// tallies, for each confirmed candidate (<see cref="Knowledge.ConfirmedLayerBlendModeCatalog"/>), how
/// many of the 35 real files carry at least one real occurrence of it. N is the count of candidates
/// repeated across 2+ distinct real files -- a real, disclosed, lower bar than
/// <see cref="MultiLayerStackMiner.DefaultMinSongCount"/>'s 5-song multi-layer-stack promotion threshold,
/// since there are only 35 real files total here and this is a coarser signal (raw blend-mode presence,
/// not a full mined/promoted multi-layer stack) -- "not a one-off fluke" is the honest bar this phase can
/// actually clear with the real corpus available, not an arbitrary number.
/// Skips cleanly (never fails) when the real corpus directory is not present, matching every other
/// real-fixture test in this project.
/// </summary>
[Trait("Category", "Integration")]
public sealed class BlendModeCorpusDiversityBaselineTests
{
    private const string CorpusDirectory = @"C:\xLights";

    /// <summary>A candidate must appear in at least this many distinct real corpus files to count toward N -- "not a one-off fluke," the same repetition discipline every other mining step in this codebase applies, scaled down from <see cref="MultiLayerStackMiner.DefaultMinSongCount"/>'s 5 since only 35 real files exist here.</summary>
    private const int MinDistinctFilesToCount = 2;

    [Fact]
    public async Task RealCorpus_BlendModeCandidateDiversity_ComputesN_AndRecordsEvidence()
    {
        if (!Directory.Exists(CorpusDirectory))
        {
            return;
        }

        var xsqFiles = Directory.GetFiles(CorpusDirectory, "*.xsq", SearchOption.TopDirectoryOnly);
        if (xsqFiles.Length == 0)
        {
            return;
        }

        var filesByCandidate = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);

        foreach (var path in xsqFiles)
        {
            IReadOnlyList<ParsedEffectInstance> instances;
            try
            {
                instances = EffectAlignmentParser.Parse(path);
            }
            catch (Exception)
            {
                continue; // A malformed/unreadable real file is skipped, never fabricated as evidence.
            }

            var fileName = Path.GetFileName(path);
            foreach (var instance in instances)
            {
                var candidate = MultiLayerStackMiner.TryMapRawBlendModeToCandidate(instance.SettingsString);
                if (candidate is null)
                {
                    continue;
                }

                if (!filesByCandidate.TryGetValue(candidate, out var files))
                {
                    files = new HashSet<string>(StringComparer.Ordinal);
                    filesByCandidate[candidate] = files;
                }

                files.Add(fileName);
            }
        }

        var repeatedCandidates = filesByCandidate
            .Where(kv => kv.Value.Count >= MinDistinctFilesToCount)
            .OrderByDescending(kv => kv.Value.Count)
            .ThenBy(kv => kv.Key, StringComparer.Ordinal)
            .ToList();

        var n = repeatedCandidates.Count;

        var evidenceDir = Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", "implementation-evidence");
        Directory.CreateDirectory(evidenceDir);
        var rows = filesByCandidate
            .OrderByDescending(kv => kv.Value.Count)
            .ThenBy(kv => kv.Key, StringComparer.Ordinal)
            .Select(kv => $"| {kv.Key} | {kv.Value.Count} | {(kv.Value.Count >= MinDistinctFilesToCount ? "yes" : "no")} |");

        await File.WriteAllTextAsync(Path.Combine(evidenceDir, "PHASE-30-BLEND-MODE-DIVERSITY-N.md"), $"""
            # Phase 30 step 30.1 -- real-corpus-mined N (auto-generated by BlendModeCorpusDiversityBaselineTests)

            Real corpus: `{CorpusDirectory}\*.xsq` ({xsqFiles.Length} real files). Parsed structurally via
            `EffectAlignmentParser` (no audio analysis needed -- a raw `T_CHOICE_LayerMethod` settings-string
            reading requires no beat grid), then each raw value mapped to its confirmed candidate via
            `MultiLayerStackMiner.TryMapRawBlendModeToCandidate` (the same mapping table 30.0's own occurrence
            tally used).

            | Confirmed candidate | Distinct real files carrying it | Counts toward N (>= {MinDistinctFilesToCount} files)? |
            |---|---:|---|
            {string.Join("\n", rows)}

            **N = {n}** -- the count of confirmed candidates repeated across {MinDistinctFilesToCount}+ distinct
            real corpus files (not a one-off fluke in a single real show). This is the acceptance definition's
            own "N distinct non-default blend modes" the blend-mode diversity gate checks generated output
            against; see `LayerBlendPlannerDiversityTests` for where this number is actually applied.
            """, CancellationToken.None);

        Assert.True(n >= 1, "Expected at least one confirmed blend-mode candidate to repeat across 2+ distinct real corpus files -- see PHASE-30-BLEND-MODE-DIVERSITY-N.md for the full tally.");
    }
}
