using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;
using XlightsAI.Studio.Reference.Fixtures;

// Repeatable-invocation tool for PHASE-01 Step 003's baseline fixture corpus.
// Running this with no arguments regenerates every synthetic audio fixture and the manifest
// byte-for-byte from the recipes below (the two layout XML fixtures are hand-authored data, not
// synthesized, so this tool only hashes them — it never overwrites or edits them).
const string ToolName = "FixtureCorpusGenerator";
const string ToolVersion = "1.0.0";
const string ReferenceVersion = "PHASE-01-Step-003/1.0.0";
var generatedUtc = new DateTimeOffset(2026, 10, 10, 0, 0, 0, TimeSpan.Zero);

var repoRoot = args.Length > 0 ? args[0] : FindRepoRoot(AppContext.BaseDirectory);
var fixturesRoot = Path.Combine(repoRoot, "fixtures");
var audioDir = Path.Combine(fixturesRoot, "audio");
var layoutsDir = Path.Combine(fixturesRoot, "layouts");
Directory.CreateDirectory(audioDir);
Directory.CreateDirectory(layoutsDir);

// --- Recipe 1: synthetic notes (ascending 5-note diatonic scale) ---
double[] notesScaleHz = [261.63, 293.66, 329.63, 349.23, 392.00]; // C4 D4 E4 F4 G4
const double noteDurationSeconds = 0.3;
const int notesSampleRate = 8000;
var notesSamples = DeterministicSyntheticAudioGenerator.BuildNoteSequence(notesScaleHz, noteDurationSeconds, notesSampleRate);
var notesWav = DeterministicSyntheticAudioGenerator.EncodeWav(notesSamples, notesSampleRate);
WriteFileIfChanged(Path.Combine(audioDir, "synthetic-notes.wav"), notesWav);

// --- Recipe 2: drum pulse click track (fixed 120 BPM, 8 clicks) ---
const int clickBpm = 120;
const int clickCount = 8;
const double clickDurationSeconds = 0.02;
const double clickToneHz = 1000.0;
const int clickSampleRate = 8000;
var clickSamples = DeterministicSyntheticAudioGenerator.BuildClickTrack(clickBpm, clickCount, clickDurationSeconds, clickToneHz, clickSampleRate);
var clickWav = DeterministicSyntheticAudioGenerator.EncodeWav(clickSamples, clickSampleRate);
WriteFileIfChanged(Path.Combine(audioDir, "drum-pulse-click-track.wav"), clickWav);

// --- Recipe 3: isolated instrumental ("piano-like") phrase (4-note arpeggio, additive harmonics) ---
double[] phraseHz = [261.63, 329.63, 392.00, 523.25]; // C4 E4 G4 C5
const double phraseNoteDurationSeconds = 0.5;
const int phraseSampleRate = 8000;
var phraseSamples = DeterministicSyntheticAudioGenerator.BuildHarmonicPhrase(phraseHz, phraseNoteDurationSeconds, phraseSampleRate);
var phraseWav = DeterministicSyntheticAudioGenerator.EncodeWav(phraseSamples, phraseSampleRate);
WriteFileIfChanged(Path.Combine(audioDir, "instrumental-piano-phrase.wav"), phraseWav);

// --- Recipe 4: complex mixed song (melody + click track summed; both fully synthetic sources) ---
double[] melodyHz = [392.00, 440.00, 493.88]; // G4 A4 B4
const double mixedNoteDurationSeconds = 1.0; // 3 notes * 1.0s = 3.0s
const int mixedSampleRate = 8000;
var melodyForMix = DeterministicSyntheticAudioGenerator.BuildNoteSequence(melodyHz, mixedNoteDurationSeconds, mixedSampleRate);
var clicksForMix = DeterministicSyntheticAudioGenerator.BuildClickTrack(bpm: 120, clickCount: 6, clickDurationSeconds: 0.02, toneHz: 800.0, sampleRate: mixedSampleRate); // 6 * 0.5s = 3.0s
var mixedSamples = DeterministicSyntheticAudioGenerator.MixDown(melodyForMix, clicksForMix);
var mixedWav = DeterministicSyntheticAudioGenerator.EncodeWav(mixedSamples, mixedSampleRate);
WriteFileIfChanged(Path.Combine(audioDir, "complex-mixed-song.wav"), mixedWav);

// --- Layout shapes: hand-authored XML fixtures; this tool only hashes what already exists on disk. ---
var layoutAPath = Path.Combine(layoutsDir, "layout-shape-a-arch-megatree.xml");
var layoutBPath = Path.Combine(layoutsDir, "layout-shape-b-matrix-stars.xml");
if (!File.Exists(layoutAPath) || !File.Exists(layoutBPath))
{
    throw new InvalidOperationException(
        "Layout XML fixtures are hand-authored and must already exist on disk; this tool does not synthesize layouts.");
}

var fixtures = new List<FixtureEntry>
{
    new(
        Id: "synthetic-notes",
        Kind: FixtureKind.SyntheticNotes,
        RelativePath: "audio/synthetic-notes.wav",
        Sha256: HashFile(Path.Combine(audioDir, "synthetic-notes.wav")),
        PermittedUsage: "Fully synthetic sine-tone generation; no copyrighted recording involved; unrestricted internal test use and redistribution.",
        LicenseNote: "Generated by this repository's own deterministic synthesizer (DeterministicSyntheticAudioGenerator); no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["sampleRateHz"] = notesSampleRate.ToString(),
            ["durationSeconds"] = (notesScaleHz.Length * noteDurationSeconds).ToString("0.0"),
            ["noteCount"] = notesScaleHz.Length.ToString(),
        }),
    new(
        Id: "drum-pulse-click-track",
        Kind: FixtureKind.DrumPulseClickTrack,
        RelativePath: "audio/drum-pulse-click-track.wav",
        Sha256: HashFile(Path.Combine(audioDir, "drum-pulse-click-track.wav")),
        PermittedUsage: "Fully synthetic tone-burst generation; no copyrighted recording involved; unrestricted internal test use and redistribution.",
        LicenseNote: "Generated by this repository's own deterministic synthesizer; no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["sampleRateHz"] = clickSampleRate.ToString(),
            ["bpm"] = clickBpm.ToString(),
            ["clickCount"] = clickCount.ToString(),
            ["durationSeconds"] = (clickCount * 60.0 / clickBpm).ToString("0.0"),
        }),
    new(
        Id: "instrumental-piano-phrase",
        Kind: FixtureKind.InstrumentalPhrase,
        RelativePath: "audio/instrumental-piano-phrase.wav",
        Sha256: HashFile(Path.Combine(audioDir, "instrumental-piano-phrase.wav")),
        PermittedUsage: "Fully synthetic additive-harmonic generation; no copyrighted recording involved; unrestricted internal test use and redistribution.",
        LicenseNote: "Generated by this repository's own deterministic synthesizer; no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["sampleRateHz"] = phraseSampleRate.ToString(),
            ["noteCount"] = phraseHz.Length.ToString(),
            ["durationSeconds"] = (phraseHz.Length * phraseNoteDurationSeconds).ToString("0.0"),
        }),
    new(
        Id: "complex-mixed-song",
        Kind: FixtureKind.ComplexMixedSong,
        RelativePath: "audio/complex-mixed-song.wav",
        Sha256: HashFile(Path.Combine(audioDir, "complex-mixed-song.wav")),
        PermittedUsage: "Fully synthetic mix of two generated sources (melody + click track); no copyrighted recording involved; unrestricted internal test use and redistribution.",
        LicenseNote: "Generated by this repository's own deterministic synthesizer; no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["sampleRateHz"] = mixedSampleRate.ToString(),
            ["sourceCount"] = "2",
            ["durationSeconds"] = (melodyHz.Length * mixedNoteDurationSeconds).ToString("0.0"),
        }),
    new(
        Id: "layout-shape-a-arch-megatree",
        Kind: FixtureKind.LayoutShape,
        RelativePath: "layouts/layout-shape-a-arch-megatree.xml",
        Sha256: HashFile(layoutAPath),
        PermittedUsage: "Hand-authored synthetic fixture, not exported from a real show; unrestricted internal test use and redistribution.",
        LicenseNote: "Authored directly for this repository; no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["modelCount"] = "2",
            ["modelGroupCount"] = "1",
        }),
    new(
        Id: "layout-shape-b-matrix-stars",
        Kind: FixtureKind.LayoutShape,
        RelativePath: "layouts/layout-shape-b-matrix-stars.xml",
        Sha256: HashFile(layoutBPath),
        PermittedUsage: "Hand-authored synthetic fixture, not exported from a real show; unrestricted internal test use and redistribution.",
        LicenseNote: "Authored directly for this repository; no third-party rights apply.",
        ReferenceVersion: ReferenceVersion,
        ExpectedOutputs: new Dictionary<string, string>
        {
            ["modelCount"] = "3",
            ["modelGroupCount"] = "2",
        }),
};

var manifest = new FixtureCorpusManifest(
    SchemaVersion: 1,
    GeneratedByTool: ToolName,
    GeneratedWithToolVersion: ToolVersion,
    GeneratedUtc: generatedUtc,
    Fixtures: fixtures);

var jsonOptions = new JsonSerializerOptions
{
    WriteIndented = true,
    PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    Converters = { new JsonStringEnumConverter() },
};
var manifestJson = JsonSerializer.Serialize(manifest, jsonOptions);
var manifestPath = Path.Combine(fixturesRoot, "FIXTURE-CORPUS-MANIFEST.json");
File.WriteAllText(manifestPath, manifestJson + Environment.NewLine);

Console.WriteLine($"Wrote {fixtures.Count} fixtures and manifest to '{fixturesRoot}'.");
foreach (var f in fixtures)
{
    Console.WriteLine($"  {f.Id,-32} {f.Sha256}");
}

return;

static void WriteFileIfChanged(string path, byte[] content)
{
    if (File.Exists(path) && File.ReadAllBytes(path).SequenceEqual(content))
    {
        return; // already byte-identical: repeatable invocation, nothing to rewrite.
    }

    File.WriteAllBytes(path, content);
}

static string HashFile(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant();

static string FindRepoRoot(string startDir)
{
    var dir = new DirectoryInfo(startDir);
    while (dir is not null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "XlightsAI.Studio.slnx")))
        {
            return dir.FullName;
        }

        dir = dir.Parent;
    }

    throw new InvalidOperationException($"Could not locate repo root (XlightsAI.Studio.slnx) above '{startDir}'.");
}
